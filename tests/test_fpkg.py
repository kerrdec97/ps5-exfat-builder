def make_dump(base, name='PPSA01234-app', extra=None):
    d = os.path.join(base, name)
    files = {
        'eboot.bin': b'\x7fELF' + b'\0' * 1000,
        'sce_sys/param.json': json.dumps({
            'contentId': CID, 'contentVersion': '01.000.000',
            'masterVersion': '01.000.000', 'applicationCategoryType': 0,
            'applicationDrmType': 'free',
            'localizedParameters': {'defaultLanguage': 'en-US'}}).encode(),
        'sce_sys/keystone': b'K' * 96,
        'sce_sys/icon0.png': b'\x89PNG',
        'sce_sys/param.sfo': b'sfo',            # generated by the SDK
        'sce_sys/about/right.sprx': b'x',       # generated by the SDK
        'sce_module/libc.prx': b'\x54\x14\xf5\xee' + b'\0' * 100,
        'Data/b.pak': b'b' * 300,
        'Data/A.pak': b'a' * 200,
        '._eboot.bin': b'appledouble',
        'Thumbs.db': b'x',
        'old.exfat': b'image',
    }
    files.update(extra or {})
    for rel, data in files.items():
        p = os.path.join(d, *rel.split('/'))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'wb') as f:
            f.write(data)
    os.makedirs(os.path.join(d, 'addcont0'))
    return d


class ParamTests(unittest.TestCase):
    def test_output_name_and_version_tag(self):
        self.assertEqual(P.version_tag('01.000.000'), '0100')
        self.assertEqual(P.version_tag('01.512.000'), '01512')
        prm = {'contentId': CID, 'contentVersion': '01.020.000'}
        self.assertEqual(P.output_name(prm), CID + '-A0120-V0120.pkg')
        self.assertTrue(P.output_name(prm, update=True).startswith('UPDATE_'))

    def test_bad_content_id_rejected(self):
        with self.assertRaises(P.ParamError):
            P.content_id({'contentId': 'PPSA01234'})

    def test_normalise_drm_and_size_class(self):
        prm = {'applicationDrmType': 'free', 'applicationCategoryType': 0,
               'kernel': {'addcontMountLevel': 2}}
        out, notes = P.normalise(prm, 10 * 1024**3, 100)
        self.assertEqual(out['applicationDrmType'], 'standard')
        self.assertEqual(out['attributePub'], 0)
        self.assertEqual(out['kernel']['addcontMountLevel'], 2)
        self.assertEqual(prm['applicationDrmType'], 'free')  # input untouched
        big, notes = P.normalise(prm, 170 * 10**9, 100)
        self.assertEqual(big['attributePub'], 1)
        self.assertEqual(big['kernel']['addcontMountLevel'], 0)
        self.assertTrue(any('WARNING' in n for n in notes))
        with self.assertRaises(P.ParamError):
            P.normalise(prm, 300 * 10**9, 100)

    def test_update_builds_keep_size_class(self):
        out, _ = P.normalise({'applicationCategoryType': 0}, 1, 1, full_app=False)
        self.assertNotIn('attributePub', out)

    def test_dump_uses_crlf(self):
        self.assertIn('\r\n', P.dump({'a': 1}))


class ScanTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='fpkg_scan_')
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def test_exclusions_order_and_empty_dirs(self):
        d = make_dump(self.tmp)
        r = S.scan(d)
        rels = [f[0] for f in r.files]
        self.assertIn('eboot.bin', rels)
        self.assertIn('sce_sys/keystone', rels)
        for gone in ('sce_sys/param.sfo', 'sce_sys/about/right.sprx',
                     '._eboot.bin', 'Thumbs.db', 'old.exfat'):
            self.assertNotIn(gone, rels)
        excluded = dict(r.excluded)
        self.assertIn('sce_sys/about', excluded)
        # casefold order within a folder: A.pak before b.pak
        self.assertLess(rels.index('Data/A.pak'), rels.index('Data/b.pak'))
        self.assertEqual(r.empty_dirs, ['addcont0'])
        self.assertTrue(r.has_keystone)
        self.assertEqual(r.total_bytes, sum(f[2] for f in r.files))

    def test_bad_names_collected(self):
        extra = {'Data/50%.pak': b'x', 'Data/semi;colon.pak': b'z'}
        if os.name != 'nt':
            # Windows itself cannot create a name ending in a dot.
            extra['Data/trail.'] = b'y'
        d = make_dump(self.tmp, extra=extra)
        r = S.scan(d)
        self.assertEqual(len(r.bad_paths), len(extra))
        self.assertTrue(all(why for _rel, why in r.bad_paths))

    def test_path_rules(self):
        self.assertIsNone(S._path_problem('Data/ok_name-1.pak'))
        self.assertTrue(S._path_problem('Data/trail.'))
        self.assertTrue(S._path_problem('Data/space '))
        self.assertTrue(S._path_problem('Dätä/x.pak'))

    def test_not_an_app_folder(self):
        os.makedirs(os.path.join(self.tmp, 'empty'))
        with self.assertRaises(S.ScanError):
            S.scan(os.path.join(self.tmp, 'empty'))

    @unittest.skipIf(os.name == 'nt', 'symlink creation needs privileges on Windows')
    def test_symlinks_rejected(self):
        d = make_dump(self.tmp)
        os.symlink(os.path.join(d, 'eboot.bin'), os.path.join(d, 'link.bin'))
        with self.assertRaises(S.ScanError):
            S.scan(d)

    def test_ps4_self_magic_reported(self):
        d = make_dump(self.tmp, extra={'sce_module/old.sprx': b'\x4f\x15\x3d\x1d' + b'\0' * 10})
        self.assertEqual(S.scan(d).self_ps4_magic, ['sce_module/old.sprx'])


class PlayGoAndGp5Tests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='fpkg_pg_')
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def test_every_chunk_has_data_and_every_scenario_lists_all(self):
        d = make_dump(self.tmp, extra={'sce_sys/playgo-scenario.json': json.dumps({
            'chunkDefaultLanguage': 'en-US',
            'chunkSupportedLanguages': ['en-US', 'fr-FR', 'xx-XX']}).encode()})
        lay = playgo.build_layout(d, 'en-US', 5)
        self.assertEqual(lay.languages, ['en-US', 'fr-FR'])
        chunks_with_data = {0} | {c for _d, c, _l in lay.payloads}
        self.assertEqual(chunks_with_data, set(range(5)))
        for sc in lay.scenario_json['scenarios']:
            self.assertEqual(sc['chunks'], list(range(5)))
            self.assertEqual(sc['initialChunkCount'], 5)
        written = playgo.write_payloads(lay, os.path.join(self.tmp, 'assets'))
        self.assertTrue(all(os.path.getsize(p) == playgo.PLACEHOLDER_SIZE
                            for _d, p, _c in written))

    def test_single_chunk_has_no_payloads(self):
        d = make_dump(self.tmp)
        lay = playgo.build_layout(d, 'en-US', 1)
        self.assertEqual(lay.payloads, [])
        self.assertEqual(playgo.chunk_range_text(1), '0')

    def test_chunk_count_limits(self):
        d = make_dump(self.tmp)
        for bad in (0, 256, 'x'):
            with self.assertRaises(playgo.PlayGoError):
                playgo.build_layout(d, 'en-US', bad)

    def test_gp5_document(self):
        d = make_dump(self.tmp)
        lay = playgo.build_layout(d, 'en-US', 3)
        files = [('eboot.bin', os.path.join(d, 'eboot.bin'), 0, None),
                 ('a&b "q".bin', 'C:\\x\\a&b.bin', 0, {'pfs_compression': 'disable'})]
        text = gp5.build_xml(CID, lay, files, ['addcont0'])
        self.assertTrue(text.startswith("<?xml version='1.0' encoding='utf-8'?>\r\n"))
        self.assertNotIn('\n', text.replace('\r\n', ''))
        root = ET.fromstring(text.encode('utf-8'))
        self.assertEqual(root.get('fmt'), 'gp5')
        self.assertEqual(root.find('volume/volume_type').text, 'prospero_app')
        self.assertEqual(root.find('volume/package').get('content_id'), CID)
        ci = root.find('volume/chunk_info')
        self.assertEqual(ci.get('chunk_count'), '3')
        self.assertEqual(len(ci.findall('chunks/chunk')), 3)
        self.assertEqual(ci.find('scenarios/scenario').text, '0-2')
        fl = root.findall('files/file')
        self.assertEqual(fl[1].get('dst_path'), 'a&b "q".bin')
        self.assertEqual(fl[1].get('pfs_compression'), 'disable')
        self.assertEqual(root.find('files/empty_dir').get('dst_path'), 'addcont0')


class RunnerTests(unittest.TestCase):
    def test_classify(self):
        self.assertEqual(runner.classify('[Error] boom'), 'error')
        self.assertEqual(runner.classify('[Warn] Process finished with warning(s)'), 'info')
        self.assertEqual(runner.classify('[Warn] real problem'), 'warn')
        self.assertIsNone(runner.classify('|____|____|'))
        self.assertIsNone(runner.classify('====='))
        self.assertTrue(runner.explain(['[Error] Format of the png file is not valid (x)']))

    def test_bar_parser_counts_equals_without_newlines(self):
        lines, fr = [], []
        bp = runner._BarParser(lines.append, fr.append)
        bp.feed('[Info] Creating an image...\r\n|____|____|\n0   20  40\n')
        bp.feed('=' * 25)
        bp.feed('=' * 26 + '\n[Info] done key=value\n')
        bp.close()
        self.assertAlmostEqual(fr[-1], 1.0)
        self.assertEqual(len(fr), 51)
        self.assertIn('[Info] done key=value', lines)

    def test_run_real_process_progress_and_errors(self):
        script = ('import sys,time\n'
                  'print("|____|")\n'
                  'sys.stdout.flush()\n'
                  'for i in range(51):\n'
                  '    sys.stdout.write("="); sys.stdout.flush()\n'
                  'print()\n'
                  'print("[Error] bad thing")\n')
        fr = []
        rr = runner.run([sys.executable, '-c', script],
                        progress=lambda f, b: f is not None and fr.append(f))
        self.assertEqual(rr.returncode, 0)
        self.assertEqual(rr.errors, ['[Error] bad thing'])
        self.assertFalse(rr.ok)          # an [Error] line fails exit code 0
        self.assertAlmostEqual(fr[-1], 1.0)

    def test_cancel_kills_process(self):
        flag = {'stop': False}
        t = threading.Timer(0.5, lambda: flag.__setitem__('stop', True))
        t.start()
        t0 = time.time()
        rr = runner.run([sys.executable, '-c', 'import time; time.sleep(60)'],
                        cancel_check=lambda: flag['stop'], poll=0.05)
        self.assertTrue(rr.cancelled)
        self.assertLess(time.time() - t0, 20)


class VerifyTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='fpkg_v_')
        self.addCleanup(shutil.rmtree, self.tmp, True)
        sys.path.insert(0, os.path.dirname(FAKE))
        self.addCleanup(sys.path.remove, os.path.dirname(FAKE))
        import fake_pubcmd
        self.fake = fake_pubcmd

    def test_debug_package_passes(self):
        p = os.path.join(self.tmp, 'a.pkg')
        self.fake.write_pkg(p)
        c = verify.check_header(p)
        self.assertTrue(c.ok, c.problems)
        self.assertTrue(c.plaintext)

    def test_stock_package_fails(self):
        p = os.path.join(self.tmp, 'a.pkg')
        self.fake.write_pkg(p, marker=False)
        c = verify.check_header(p)
        self.assertFalse(c.ok)
        self.assertIn('marker', ' '.join(c.problems))

    def test_garbage_and_signed(self):
        p = os.path.join(self.tmp, 'a.pkg')
        with open(p, 'wb') as f:
            f.write(b'\0' * 5000)
        self.assertFalse(verify.check_header(p).ok)
        self.fake.write_pkg(p)
        with open(p, 'r+b') as f:
            f.seek(5)
            f.write(b'\x01')
        self.assertIn('signed', ' '.join(verify.check_header(p).problems))


@unittest.skipIf(os.name == 'nt', 'the fake Publishing Tools is a script')
class EndToEnd(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix='fpkg_e2e_')
        self.addCleanup(shutil.rmtree, self.tmp, True)
        tools = os.path.join(self.tmp, 'tools')
        os.makedirs(os.path.join(tools, 'ext'))
        open(os.path.join(tools, 'libScePubTools.dll'), 'wb').close()
        self.exe = os.path.join(tools, 'prospero-pub-cmd.exe')
        with open(self.exe, 'w') as f:
            f.write('#!%s\nimport runpy, sys\nsys.argv[0] = %r\n'
                    'runpy.run_path(%r, run_name="__main__")\n'
                    % (sys.executable, FAKE, FAKE))
        os.chmod(self.exe, os.stat(self.exe).st_mode | stat.S_IEXEC)
        self.dump = make_dump(self.tmp)
        self.out = os.path.join(self.tmp, 'out')
        self.addCleanup(os.environ.pop, 'FAKE_PUBCMD_MODE', None)
        self.addCleanup(os.environ.pop, 'FAKE_PUBCMD_VERIFY', None)

    def build(self, **kw):
        logs, prog = [], []
        cancel = kw.pop('cancel_check', None)
        opts = backend.FpkgOptions(self.dump, self.out, tool_path=self.exe,
                                   chunk_count=kw.pop('chunk_count', 4), **kw)
        r = backend.build_fpkg(opts, log=logs.append,
                               progress=lambda p, s: prog.append((p, s)),
                               cancel_check=cancel)
        return r, logs, prog

    def test_successful_build(self):
        r, logs, prog = self.build()
        self.assertIs(r.status, True, '\n'.join(logs))
        self.assertEqual(os.path.basename(r.out_path), CID + '-A0100-V0100.pkg')
        self.assertTrue(verify.check_header(r.out_path).ok)
        self.assertEqual(prog[-1][0], 100)
        self.assertTrue(any(p and 40 < p < 94 for p, _s in prog))
        left = sorted(os.listdir(self.out))
        self.assertEqual(left, [CID + '-A0100-V0100-build-logs',
                                CID + '-A0100-V0100.pkg'])
        with open(os.path.join(r.log_dir, '02-img-create.log')) as f:
            self.assertIn('exit_code=0', f.read())

    def test_project_contents(self):
        r, logs, _ = self.build(keep_intermediate=True)
        self.assertIs(r.status, True, '\n'.join(logs))
        stem = CID + '-A0100-V0100'
        root = ET.parse(os.path.join(self.out, stem + '.gp5')).getroot()
        files = {f.get('dst_path'): f for f in root.iter('file')}
        self.assertIn('sce_sys/playgo-scenario.json', files)
        self.assertIn('.gp5-assets', files['sce_sys/param.json'].get('src_path'))
        with open(files['sce_sys/param.json'].get('src_path'), encoding='utf-8') as f:
            self.assertEqual(json.load(f)['applicationDrmType'], 'standard')
        self.assertNotIn('sce_sys/param.sfo', files)
        self.assertEqual([e.get('dst_path') for e in root.iter('empty_dir')], ['addcont0'])

    def test_stock_tools_output_is_a_failure(self):
        os.environ['FAKE_PUBCMD_MODE'] = 'stock'
        r, logs, _ = self.build()
        self.assertIs(r.status, False)
        self.assertIn('marker', ' '.join(r.messages))
        self.assertFalse([n for n in os.listdir(self.out) if n.endswith('.pkg')])

    def test_error_line_fails_even_with_exit_0(self):
        os.environ['FAKE_PUBCMD_MODE'] = 'error'
        r, _logs, _ = self.build()
        self.assertIs(r.status, False)
        self.assertIn('png', ' '.join(r.messages).lower())
        self.assertFalse([n for n in os.listdir(self.out) if n.endswith('.pkg')])

    def test_exit_code_and_no_output(self):
        for mode in ('crash', 'nooutput'):
            os.environ['FAKE_PUBCMD_MODE'] = mode
            r, _l, _p = self.build()
            self.assertIs(r.status, False, mode)

    def test_verify_failure_is_a_warning_and_keeps_package(self):
        os.environ['FAKE_PUBCMD_VERIFY'] = 'fail'
        r, _l, _p = self.build()
        self.assertEqual(r.status, 'warn')
        self.assertTrue(os.path.isfile(r.out_path))

    def test_existing_package_is_not_overwritten(self):
        r1, _l, _p = self.build()
        r2, _l, _p = self.build()
        self.assertNotEqual(r1.out_path, r2.out_path)
        self.assertTrue(os.path.isfile(r1.out_path) and os.path.isfile(r2.out_path))

    def test_cancel_removes_partial(self):
        os.environ['FAKE_PUBCMD_MODE'] = 'slow'
        flag = {'stop': False}
        threading.Timer(1.5, lambda: flag.__setitem__('stop', True)).start()
        r, _l, _p = self.build(cancel_check=lambda: flag['stop'])
        self.assertIsNone(r.status)
        self.assertFalse([n for n in os.listdir(self.out) if '.pkg' in n])

    def test_update_build(self):
        base = os.path.join(self.tmp, 'base.pkg')
        open(base, 'wb').close()
        r, logs, _ = self.build(ref_pkg=base)
        self.assertIs(r.status, True, '\n'.join(logs))
        self.assertTrue(os.path.basename(r.out_path).startswith('UPDATE_'))
        self.assertTrue(r.companion_path.endswith('.remastered.pkg'))

    def test_preflight_failures(self):
        os.remove(os.path.join(self.dump, 'sce_sys', 'keystone'))
        r, _l, _p = self.build()
        self.assertIs(r.status, False)
        self.assertIn('keystone', ' '.join(r.messages))
        r = backend.build_fpkg(backend.FpkgOptions(self.dump, self.out,
                                                   tool_path=os.path.join(self.tmp, 'nope')))
        self.assertIs(r.status, False)
        self.assertIn('Publishing Tools', ' '.join(r.messages))



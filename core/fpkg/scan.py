"""Walk a PS5 app folder and decide what goes into the package.

Order matters: Publishing Tools lays the image out in project order, so
entries are listed by a recursive walk with each folder sorted by
``name.casefold()``. Files the SDK generates itself, dump leftovers and
OS junk are left out; every exclusion is recorded with its reason.
"""
import os

# Files directly in sce_sys/ that the SDK generates or that belong to the
# original package. The keystone is kept: the debug toolchain needs the
# dump's own 96-byte keystone.
SCE_SYS_GENERATED = frozenset(n.lower() for n in (
    'pfs-version.dat', 'disc_info.dat', 'ext_info.dat', 'imagedigs.dat',
    'license.info', 'license.dat', 'playgo-chunk.dat', 'playgo-hash-table.dat',
    'playgo-ficm.dat', 'playgo-scenario.json', 'playgo-manifest.xml',
    'playgo-chunk.crc', 'pfsimage.xml', 'pfs-region-hints.json', 'param.sfo',
    'param_cp_values.json', 'pronunciation.sig', 'origin-deltainfo.dat',
    'target-deltainfo.dat', 'origin-param.json', 'target-param.json',
    'origin-relocinfo.dat', 'target-relocinfo.dat'))
SCE_SYS_GENERATED_EXT = ('.dds', '.auth_info')
ROOT_EXCLUDED_DIRS = frozenset(('sce_suppl', 'sce_sc', '.gp5-assets'))
ANYWHERE_EXT = ('.gp4', '.gp5', '.esbak', '.playgo-scenario.json')
FAKELIB_EXCLUDED = frozenset(('libsceampr.sprx', 'libsceplaygo.sprx'))
JUNK_FILES = frozenset(('.ds_store', 'thumbs.db', 'desktop.ini', '.localized'))
JUNK_DIRS = frozenset(d.lower() for d in (
    '__MACOSX', '.Spotlight-V100', '.fseventsd', '.Trashes', '.TemporaryItems',
    '.AppleDouble', '$RECYCLE.BIN', 'System Volume Information'))
# The output of the exFAT Image Builder itself, should one sit in the dump.
IMAGE_EXT = ('.exfat', '.ffpkg', '.ffpfs', '.ffpfsc', '.pkg')

BAD_PATH_CHARS = set('%;')


class ScanError(Exception):
    pass


class ScanResult:
    def __init__(self):
        self.files = []        # (dst_rel posix path, abs src path, size)
        self.empty_dirs = []   # dst_rel posix paths
        self.excluded = []     # (rel, reason)
        self.bad_paths = []    # (rel, reason)
        self.total_bytes = 0
        self.has_keystone = False
        self.keystone_size = None
        self.self_ps4_magic = []   # rel paths of PS4-magic SELF files

    @property
    def file_count(self):
        return len(self.files)


def _exclusion(rel_parts, name, is_dir):
    """Reason string if this entry is excluded, else None."""
    low = name.lower()
    depth = len(rel_parts)
    if is_dir:
        if low in JUNK_DIRS:
            return 'OS metadata folder'
        if depth == 0 and low in ROOT_EXCLUDED_DIRS:
            return 'not part of an app package'
        if depth == 1 and rel_parts[0].lower() == 'sce_sys' and low == 'about':
            return 'generated by the SDK (sce_sys/about)'
        if low == 'decrypted' and depth == 0:
            return 'dumper working folder'
        return None
    if low in JUNK_FILES or low.startswith('._') or low.endswith('.url') \
            or (low.startswith('ehthumbs') and low.endswith('.db')):
        return 'OS metadata file'
    if low.endswith(ANYWHERE_EXT):
        return 'project/backup file'
    if depth == 0 and (low == 'ampr_emu.index' or low.endswith(IMAGE_EXT)):
        return 'tool output, not game data'
    if depth == 1 and rel_parts[0].lower() == 'sce_sys':
        if low in SCE_SYS_GENERATED:
            return 'generated by the SDK'
        if low.endswith(SCE_SYS_GENERATED_EXT):
            return 'generated by the SDK'
    if depth == 1 and rel_parts[0].lower() == 'fakelib' and low in FAKELIB_EXCLUDED:
        return 'dump emulation library (PlayGo/AMPR)'
    return None


def _path_problem(rel):
    try:
        rel.encode('ascii')
    except UnicodeEncodeError:
        return 'non-ASCII characters'
    if BAD_PATH_CHARS & set(rel):
        return "contains '%' or ';'"
    for part in rel.split('/'):
        if part.endswith('.') or part.endswith(' '):
            return 'a name ends with a dot or space'
    return None


def scan(app_dir, cancel_check=None, require_eboot=True):
    """Scan `app_dir`. Raises ScanError for symlinks/junctions and when
    the folder is not a PS5 app (`require_eboot`; add-ons have no
    eboot.bin); path-rule problems are collected in `bad_paths` so they
    can all be shown at once."""
    if not os.path.isdir(app_dir):
        raise ScanError('Folder not found: %s' % app_dir)
    if require_eboot and not os.path.isfile(os.path.join(app_dir, 'eboot.bin')):
        raise ScanError('eboot.bin was not found in the folder root; this is '
                        'not a PS5 app folder.')
    res = ScanResult()
    seen = [0]

    def walk(abs_dir, rel_parts):
        try:
            entries = sorted(os.scandir(abs_dir), key=lambda e: e.name.casefold())
        except OSError as e:
            raise ScanError('Cannot read %s: %s' % (abs_dir, e))
        kept_any = False
        for e in entries:
            seen[0] += 1
            if cancel_check and seen[0] % 2000 == 0 and cancel_check():
                raise ScanError('cancelled')
            rel = '/'.join(rel_parts + [e.name])
            if e.is_symlink() or _is_junction(e.path):
                raise ScanError('Links are not supported in a package: %s' % rel)
            is_dir = e.is_dir(follow_symlinks=False)
            why = _exclusion(rel_parts, e.name, is_dir)
            if why:
                res.excluded.append((rel, why))
                continue
            if is_dir:
                walk(e.path, rel_parts + [e.name])
                kept_any = True
                continue
            if not e.is_file(follow_symlinks=False):
                res.excluded.append((rel, 'not a regular file'))
                continue
            prob = _path_problem(rel)
            if prob:
                res.bad_paths.append((rel, prob))
            size = e.stat(follow_symlinks=False).st_size
            if rel.lower() == 'sce_sys/keystone':
                res.has_keystone = True
                res.keystone_size = size
            if e.name.lower().endswith(('.sprx', '.prx', '.self')) or \
                    e.name.lower() == 'eboot.bin':
                try:
                    with open(e.path, 'rb') as f:
                        if f.read(4) == b'\x4f\x15\x3d\x1d':
                            res.self_ps4_magic.append(rel)
                except OSError:
                    pass
            res.files.append((rel, e.path, size))
            res.total_bytes += size
            kept_any = True
        if not kept_any and rel_parts and rel_parts[0].lower() != 'sce_sys':
            res.empty_dirs.append('/'.join(rel_parts))

    walk(os.path.abspath(app_dir), [])
    return res


def _is_junction(path):
    fn = getattr(os.path, 'isjunction', None)
    try:
        return bool(fn and fn(path))
    except OSError:
        return False

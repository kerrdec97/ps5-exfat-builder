bool isJunkFileName(const QString& name)
{
    const QString low = name.toLower();
    if (low == u".ds_store" || low == u"thumbs.db" || low == u"desktop.ini" || low == u".localized")
        return true;
    if (low.startsWith(QStringLiteral("._")))
        return true;
    if (low.endsWith(QStringLiteral(".url")))
        return true;
    if (low.startsWith(QStringLiteral("ehthumbs")) && low.endsWith(QStringLiteral(".db")))
        return true;
    return false;
}

bool isJunkDirName(const QString& name)
{
    static const QSet<QString> dirs = {
        QStringLiteral("__macosx"),     QStringLiteral(".spotlight-v100"), QStringLiteral(".fseventsd"),
        QStringLiteral(".trashes"),     QStringLiteral(".temporaryitems"), QStringLiteral(".appledouble"),
        QStringLiteral("$recycle.bin"), QStringLiteral("system volume information"),
    };
    return dirs.contains(name.toLower());
}

QString pathRuleProblem(const QString& dst)
{
    for (const QChar c : dst) {
        const char16_t u = c.unicode();
        if (u > 0x7E)
            return QStringLiteral("non-ASCII characters");
        if (u < 0x20)
            return QStringLiteral("control characters");
        if (u == u'%' || u == u';')
            return QStringLiteral("contains '%' or ';'");
    }
    const QStringList parts = dst.split(u'/');
    for (const QString& p : parts) {
        if (p.isEmpty())
            return QStringLiteral("an empty folder name");
        if (p.endsWith(u'.'))
            return QStringLiteral("a name ends with a dot");
    }
    return {};
}

QString baseExclusionReason(const QStringList& parts, const QString& name, bool isDir)
{
    const QString low = folded(name);
    const qsizetype depth = parts.size();
    const bool inSceSys = depth >= 1 && eqi(parts[0], QStringLiteral("sce_sys"));
    if (isDir) {
        if (isJunkDirName(name))
            return QStringLiteral("OS metadata folder");
        if (depth == 0 && (low == u".gp5-assets" || low == u"sce_suppl" || low == u"sce_sc"))
            return QStringLiteral("not part of an app package");
        if (depth == 0 && low == u"decrypted")
            return QStringLiteral("dumper working folder");
        if (depth == 1 && inSceSys && low == u"about")
            return QStringLiteral("generated by the SDK (sce_sys/about)");
        return {};
    }
    if (isJunkFileName(name))
        return QStringLiteral("OS metadata file");
    if (endsWithAny(low, {".gp4", ".gp5", ".esbak", ".playgo-scenario.json"}))
        return QStringLiteral("project or backup file");
    if (depth == 0 && low == u"ampr_emu.index")
        return QStringLiteral("AMPR emulator index");
    if (depth == 0 && endsWithAny(low, {".exfat", ".ffpkg", ".ffpfs", ".ffpfsc", ".pkg"}))
        return QStringLiteral("image or package file, not game data");
    if (depth == 1 && eqi(parts[0], QStringLiteral("fakelib"))
        && (low == u"libsceampr.sprx" || low == u"libsceplaygo.sprx"))
        return QStringLiteral("dump emulation library (AMPR/PlayGo)");
    if (depth == 1 && inSceSys && sdkGeneratedSceSysFiles().contains(low))
        return QStringLiteral("generated by the SDK");
    if (inSceSys && endsWithAny(low, {".dds", ".auth_info"}))
        return QStringLiteral("generated by the SDK");
    return {};
}

QString leftoverReason(const QStringList& parts, const QString& name, bool isDir, const LeftoverOptions& o,
                       const LeftoverContext& ctx)
{
    const QString low = folded(name);
    const qsizetype depth = parts.size();
    if (!o.keepDlcEmulator && !isDir) {
        if (depth == 0 && low == u"dlc_emu.ini")
            return QStringLiteral("DLC emulator (\"Keep the DLC emulator\" is off)");
        if (depth == 1 && isFakelibDir(parts[0])) {
            static const QSet<QString> mods = {
                QStringLiteral("libsceappcontent.sprx"),          QStringLiteral("libsceappcontent.prx"),
                QStringLiteral("libscenpentitlementaccess.sprx"), QStringLiteral("libscenpentitlementaccess.prx"),
                QStringLiteral("libscegameupdate.sprx"),          QStringLiteral("libscegameupdate.prx"),
            };
            if (mods.contains(low))
                return QStringLiteral("DLC emulator module (\"Keep the DLC emulator\" is off)");
        }
    }
    if (o.removeAmprLeftovers && !isDir) {
        if (depth == 0 && low == u"ampr_emu.index")
            return QStringLiteral("AMPR emulator leftover");
        if (depth == 1 && eqi(parts[0], QStringLiteral("fakelib"))
            && (low == u"ampr_emu.index" || low == u"libsceampr.sprx"))
            return QStringLiteral("AMPR emulator leftover");
    }
    if (o.removeDumpLeftovers && isDir) {
        if (depth == 0 && name == u"_DUBLEX_")
            return QStringLiteral("dump leftover (_DUBLEX_)");
        if (depth == 0 && low == u"engine" && ctx.childNames.size() == 1 && eqi(ctx.childNames[0], QStringLiteral("Saved")))
            return QStringLiteral("dump leftover (Unreal Engine\\Saved is its only content)");
        if (depth == 1 && low == u"saved" && eqi(parts[0], QStringLiteral("Engine")))
            return QStringLiteral("dump leftover (Unreal Engine\\Saved)");
        if (depth == 1 && low == u"saved" && ctx.rootFolderHasContentPaks)
            return QStringLiteral("dump leftover (Unreal project Saved folder)");
    }
    return {};
}

QString DlcEmuEntry::mountFolder() const
{
    QString mp = mountPoint.trimmed();
    mp.replace(u'\\', u'/');
    static const QString prefix = QStringLiteral("/app0/");
    if (!mp.startsWith(prefix, Qt::CaseInsensitive))
        return {};
    QString rel = mp.mid(prefix.size());
    while (rel.endsWith(u'/'))
        rel.chop(1);
    while (rel.startsWith(u'/'))
        rel.remove(0, 1);
    if (rel.isEmpty() || rel.contains(QStringLiteral("..")))
        return {};
    return rel;
}

DlcEmuIni parseDlcEmuIni(const QByteArray& text)
{
    DlcEmuIni ini;
    if (text.size() > kDlcEmuIniMaxBytes) {
        ini.warnings << QStringLiteral("dlc_emu.ini is larger than 64 KiB and was not read.");
        return ini;
    }
    QString s = QString::fromUtf8(text);
    if (s.startsWith(QChar(0xFEFF)))
        s.remove(0, 1);
    static const QRegularExpression sectionRe(QStringLiteral("^\\[([A-Za-z0-9_]+)\\]$"));
    std::vector<DlcEmuEntry> raw;
    bool inEntry = false;
    for (QString line : s.split(u'\n')) {
        line = line.trimmed();
        if (line.isEmpty() || line.startsWith(u'#') || line.startsWith(u';'))
            continue;
        const auto m = sectionRe.match(line);
        if (m.hasMatch()) {
            raw.push_back(DlcEmuEntry{});
            raw.back().section = m.captured(1).toUpper();
            inEntry = true;
            continue;
        }
        if (!inEntry)
            continue;
        const qsizetype eq = line.indexOf(u'=');
        if (eq <= 0)
            continue;
        const QString key = line.left(eq).trimmed().toLower();
        const QString value = line.mid(eq + 1).trimmed();
        DlcEmuEntry& e = raw.back();
        if (key == u"content_id")
            e.contentId = value;
        else if (key == u"mount_point")
            e.mountPoint = value;
        else if (key == u"download_status")
            e.downloadStatus = value;
        else if (key == u"entitlement_key")
            e.entitlementKey = value;
    }
    QSet<QString> seen;
    for (const auto& e : raw) {
        if (e.contentId.isEmpty())
            continue;
        ini.allEntries.push_back(e);
        if (e.section != u"PSAC")
            continue;
        if (seen.contains(e.contentId)) {
            ini.warnings << QStringLiteral("dlc_emu.ini lists %1 more than once; the repeat was ignored.").arg(e.contentId);
            continue;
        }
        seen.insert(e.contentId);
        ini.entries.push_back(e);
    }
    return ini;
}

bool isAddcontFolderName(const QString& name)
{
    static const QRegularExpression re(QStringLiteral("^addcont[0-9]+$"), QRegularExpression::CaseInsensitiveOption);
    return re.match(name).hasMatch();
}


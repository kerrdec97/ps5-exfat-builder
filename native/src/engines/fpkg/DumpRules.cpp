QString folded(const QString& s) { return s.toCaseFolded(); }

bool eqi(const QString& a, const QString& b) { return a.compare(b, Qt::CaseInsensitive) == 0; }

bool endsWithAny(const QString& lowerName, std::initializer_list<const char*> exts)
{
    for (const char* e : exts)
        if (lowerName.endsWith(QLatin1String(e)))
            return true;
    return false;
}


    void klogClientReconnectsAndDeliversLines()
    {
        // Each connection sends two lines and closes; the client reconnects.
        fake::FakeLineServer srv({{{0, "boot ok\n"}, {20, "[ERROR] crash\r\n"}},
                                  {{0, "second session\n"}, {10, "warn: x\n"}}},
                                 true);
        std::mutex m;
        QStringList lines;
        QList<KlogTag> tags;
        QStringList states;
        KlogClient::Options o;
        o.host = QStringLiteral("127.0.0.1");
        o.port = srv.port();
        o.reconnectDelayMs = 100;
        KlogClient client(o,
                          [&](const KlogLine& l) {
                              std::lock_guard g(m);
                              lines << l.text;
                              tags << l.tag;
                          },
                          [&](KlogState st, const QString&) {
                              std::lock_guard g(m);
                              states << klogStateName(st);
                          });
        client.start();
        QVERIFY(QTest::qWaitFor([&] { std::lock_guard g(m); return lines.size() >= 6; }, 10000));
        client.stop();
        QVERIFY(!client.isRunning());
        std::lock_guard g(m);
        QCOMPARE(lines.mid(0, 4), (QStringList{QStringLiteral("boot ok"), QStringLiteral("[ERROR] crash"),
                                               QStringLiteral("second session"), QStringLiteral("warn: x")}));
        QCOMPARE(tags.at(1), KlogTag::Error);
        QCOMPARE(tags.at(3), KlogTag::Warning);
        QVERIFY(client.connections() >= 3);
        QVERIFY(states.contains(QStringLiteral("Reconnecting")));
        QCOMPARE(states.back(), QStringLiteral("Stopped"));
        QVERIFY(client.linesReceived() >= 6);
    }

    void klogClientWithoutReconnectStops()
    {
        KlogClient::Options o;
        o.host = QStringLiteral("127.0.0.1");
        o.port = closedPort();
        o.reconnect = false;
        std::atomic<bool> stopped{false};
        KlogClient client(o, {}, [&](KlogState st, const QString&) {
            if (st == KlogState::Stopped)
                stopped = true;
        });
        client.start();
        QVERIFY(QTest::qWaitFor([&] { return stopped.load(); }, 15000)); // Windows takes ~2 s to refuse
        QCOMPARE(client.connections(), 0);
    }


    // No klog: the tail of /data/shadowmount/debug.log is followed over FTP.
    void safeToUnplugFollowsDebugLogWithoutKlog()
    {
        const QString root = fresh(QStringLiteral("smp-log"));
        const QString log = QDir(root).filePath(QStringLiteral("data/shadowmount/debug.log"));
        QVERIFY(fwtest::writeTextFile(log, "ShadowMount+ v1.7beta11 exFAT/UFS/PFS/LVD/MD. FW: 9.60.\n"
                                           "[SHUTDOWN] cleanup complete for STOP file /data/shadowmount/STOP\n")); // an old run: before the offset
        fake::FakeFtpServer::Options fo;
        fo.root = root;
        fake::FakeFtpServer ftp(fo);
        // "ShadowMount+" notices the STOP file and logs its shutdown: only once
        // the file is there, however long the PC takes to get that far (lines
        // written before the STOP would count as an old run).
        std::atomic<bool> stop{false};
        std::thread smp([&] {
            const QString stopFile = QDir(root).filePath(QStringLiteral("data/shadowmount/STOP"));
            while (!stop && !QFileInfo::exists(stopFile))
                QThread::msleep(10);
            if (stop)
                return;
            QThread::msleep(150);
            QFile f(log);
            if (f.open(QIODevice::Append)) {
                f.write("[SHUTDOWN] requested by STOP file /data/shadowmount/STOP\n");
                f.write("[SHUTDOWN] cleanup complete for STOP file /data/shadowmount/STOP\n");
            }
        });
        ConsoleEndpoint ep = endpoint(ftp.port());
        ep.klogPort = closedPort(); // nothing there
        QStringList status;
        auto r = stopShadowMount(ep, {}, [&](const QString& s) { status << s; }, 6000, 1000, 60000, 200);
        stop = true;
        smp.join();
        QVERIFY2(r.ok(), r.ok() ? "" : qPrintable(r.error().toLogString()));
        QCOMPARE(r->outcome, StopOutcome::Confirmed);
        QCOMPARE(r->source, QStringLiteral("debug.log"));
        QVERIFY(status.join(u'\n').contains(QStringLiteral("debug.log")));
        QVERIFY(ftp.sawCommand(QStringLiteral("REST ")));

        // Without debug.log there is nothing to follow: amber at once.
        QVERIFY(QFile::remove(log));
        auto none = stopShadowMount(ep, {}, {}, 2000, 1000);
        QCOMPARE(none->outcome, StopOutcome::NoKlog);
    }


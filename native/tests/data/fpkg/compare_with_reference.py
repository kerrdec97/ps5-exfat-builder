"""Compares this app's FPKG project with the reference toolkit's for the same folder.

The reference is create-gp5-from-folder.py of the Sony SDK toolkit the FPKG
builder follows (sdk-fpkg279-fix15, shipped with PSVIETHOA FPKG Builder 3.1).
The script is not part of this repository: pass its path.

What happens:
  1. a small synthetic game folder is written (no real game data);
  2. the reference script writes its project for it (GP5 only, no Sony tool runs);
  3. tst_fpkg_rules projectForComparison writes this app's project for it,
     with the app's own extras turned off (FW_FPKG_COMPARE_MODE=script);
  4. both projects are reduced to the same form and compared: chunk_info, and
     for every file its package path, chunk, compression flag and where its
     data comes from (the folder, or generated bytes, which are compared too).

Usage:
  python compare_with_reference.py --script <create-gp5-from-folder.py>
         --test-exe <build>/tests/tst_fpkg_rules.exe [--qt-bin <Qt>/bin] [--keep <dir>]

Exit code 0: identical. 1: differences (printed). 2: could not run.
"""
import argparse
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

CID = 'UP0000-PPSA01234_00-COMPARETEST00000'
PLAYGO_LANGUAGES = (
    "ja-JP", "en-US", "fr-FR", "es-ES", "de-DE", "it-IT", "nl-NL", "pt-PT",
    "ru-RU", "ko-KR", "zh-Hant", "zh-Hans", "fi-FI", "sv-SE", "da-DK", "no-NO",
    "pl-PL", "pt-BR", "en-GB", "tr-TR", "es-419", "ar-AE", "fr-CA", "cs-CZ",
    "hu-HU", "el-GR", "ro-RO", "th-TH", "vi-VN", "id-ID", "uk-UA",
)
M = (1 << 64) - 1


def put(root, rel, data):
    path = os.path.join(root, rel.replace('/', os.sep))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data if isinstance(data, bytes) else data.encode('utf-8'))


def png(color_type):
    ihdr = struct.pack('>II', 1, 1) + bytes([8, color_type, 0, 0, 0])
    return (b'\x89PNG\r\n\x1a\n' + struct.pack('>I', 13) + b'IHDR' + ihdr + bytes(4)
            + bytes(4) + b'IEND' + bytes(4))


def sceversion(name, version):
    payload = len(name) + 17
    return b'\0\0' + struct.pack('<H', payload) + b'\x08' + name + struct.pack('>Q', version) * 2


def self_file(magic, early, trailer):
    head = bytearray(0x20)
    head[0:4] = magic
    struct.pack_into('<Q', head, 0x10, 0x40)
    return bytes(head) + b'E' * (0x20 - early) + trailer


def rol(x, n):
    return ((x << n) | (x >> (64 - n))) & M


def mix(a, b, c):
    x = rol(rol(c ^ b, 5) ^ a, 53)
    y = rol(rol(c ^ a, 17) ^ b, 11)
    z = rol(rol(b ^ a, 1) ^ c, 59)
    return ((~y & z) ^ x ^ 0x8000000080008081) & M, ((~z & x) ^ y) & M, ((~x & y) ^ z) & M


def path_hash(path, seed, key):
    data = path.encode('utf-8').upper()
    a, b, c = seed, rol(seed, 11), rol(seed, 23)
    tail = 0
    if data:
        blocks, rest = divmod(len(data) - 1, 8)
        for i in range(blocks):
            a ^= struct.unpack_from('<Q', data, i * 8)[0]
            a, b, c = mix(a, b, c)
        tail = int.from_bytes(data[blocks * 8:blocks * 8 + rest + 1], 'little')
    return mix(tail ^ a ^ key, b, c)[0]


def lang_mask(codes):
    return sum(1 << (63 - PLAYGO_LANGUAGES.index(c)) for c in codes)


def playgo_tables(chunks, scenarios, file_chunks, seed, key):
    """chunks: [(label, [languages])]; scenarios: [(label, initial, [chunk ids])]; file_chunks: {path: chunk}."""
    attrs, labels = bytearray(), bytearray()
    for label, languages in chunks:
        entry = bytearray(0x20)
        struct.pack_into('<Q', entry, 0x10, lang_mask(languages))
        struct.pack_into('<I', entry, 0x1c, len(labels))
        attrs += entry
        labels += label.encode('utf-8') + b'\0'
    table, lists, names = bytearray(), bytearray(), bytearray()
    for label, initial, ids in scenarios:
        entry = bytearray(0x20)
        entry[0] = 1
        struct.pack_into('<HH', entry, 0x14, initial, len(ids))
        struct.pack_into('<II', entry, 0x18, len(lists), len(names))
        table += entry
        lists += b''.join(struct.pack('<H', i) for i in ids)
        names += label.encode('utf-8') + b'\0'
    head = bytearray(0x100)
    head[0:4] = b'plgx'
    struct.pack_into('<HH', head, 4, 0x1000, 0)
    struct.pack_into('<H', head, 0x0a, len(chunks))
    struct.pack_into('<H', head, 0x0e, len(scenarios))
    body = bytearray()
    for at, section in ((0xc0, attrs), (0xd0, labels), (0xe0, table), (0xe8, lists), (0xf0, names)):
        struct.pack_into('<II', head, at, 0x100 + len(body), len(section))
        body += section
    struct.pack_into('<I', head, 0x10, 0x100 + len(body))
    chunk_dat = bytes(head + body)

    rows = sorted((path_hash(p, seed, key), c) for p, c in file_chunks.items())
    ht = bytearray(0x38)
    struct.pack_into('<I', ht, 0, 1)
    struct.pack_into('<I', ht, 8, 0x38)
    struct.pack_into('<I', ht, 0x0c, len(rows) * 8)
    ht[0x18:0x1c] = b'\x7fFLT'
    struct.pack_into('<I', ht, 0x24, len(rows))
    struct.pack_into('<QQ', ht, 0x28, seed, key)
    ht += b''.join(struct.pack('<Q', h) for h, _ in rows)
    ficm = bytearray(0x10)
    struct.pack_into('<I', ficm, 0, 1)
    struct.pack_into('<I', ficm, 8, 0x10)
    struct.pack_into('<I', ficm, 0x0c, len(rows) * 2)
    ficm += b''.join(struct.pack('<H', c) for _, c in rows)
    return chunk_dat, bytes(ht), bytes(ficm)


def npbind(ids):
    d = bytearray(0x214)
    struct.pack_into('>I', d, 0, 0xD294A018)
    struct.pack_into('>I', d, 4, 1)
    struct.pack_into('>I', d, 0x0c, 0x214)
    struct.pack_into('>I', d, 0x14, 0x40)
    struct.pack_into('>I', d, 0x1c, len(ids))
    for i, npwr in enumerate(ids):
        at = 0x80 + i * 0x40
        struct.pack_into('>HH', d, at, 0x10, len(npwr))
        d[at + 4:at + 4 + len(npwr)] = npwr.encode('ascii')
    d[0x200:0x214] = hashlib.sha1(bytes(d[:0x200])).digest()
    return bytes(d)


def write_dump(root, variant):
    """variant: 'generated' (no PlayGo tables) or 'layout' (the dump's own chunk layout)."""
    param = {
        'contentId': CID, 'contentVersion': '01.000.000', 'masterVersion': '01.00',
        'applicationCategoryType': 0, 'applicationDrmType': 'free', 'attribute3': 4,
        'versionFileUri': 'http://example.invalid/version.xml',
        'sdkVersion': '0x0000000000000000', 'requiredSystemSoftwareVersion': '0x0000000000000000',
        'kernel': {'appSizeInGib': 5},
        'localizedParameters': {'defaultLanguage': 'en-US', 'en-US': {'titleName': 'Compare ☃'}},
    }
    scenario = {
        'chunkDefaultLanguage': 'en-US', 'chunkSupportedLanguages': ['en-US', 'fr-FR'],
        'scenarioCount': 2, 'scenarioDefaultId': 0, 'scenarioDefaultLanguage': 'en-US',
        'scenarios': [
            {'id': 0, 'type': 'playmode', 'en-US': {'title': 'Main game', 'description': 'Everything'}},
            {'id': 1, 'type': 'mp', 'en-US': {'title': 'Multiplayer', 'description': 'Online'},
             'fr-FR': {'title': 'Multi', 'description': 'En ligne'}},
        ],
    }
    trailer = sceversion(b'libc:', 0x0500003300000001) + sceversion(b'libSceFace:', 0x0600003800000001)
    put(root, 'eboot.bin', self_file(b'\x54\x14\xf5\xee', 5, trailer))          # trailer 5 bytes early
    put(root, 'sce_module/libc.prx', self_file(b'\x4f\x15\x3d\x1d', 0, trailer))  # PS4 signature
    put(root, 'sce_module/libSceFios2.prx', self_file(b'\x54\x14\xf5\xee', 0, trailer))  # fine as it is
    put(root, 'sce_sys/param.json', json.dumps(param))
    put(root, 'sce_sys/keystone', b'K' * 96)
    put(root, 'sce_sys/icon0.png', png(2))
    put(root, 'sce_sys/pic0.png', png(2))
    put(root, 'sce_sys/param.sfo', b'sfo')
    put(root, 'sce_sys/about/right.sprx', b'x')
    put(root, 'sce_sys/license.dat', b'x')
    put(root, 'sce_sys/lem_notification.dat', b'x')
    put(root, 'sce_sys/playgo-scenario.json', json.dumps(scenario))
    put(root, 'sce_sys/nptitle.dat', b'np')
    put(root, 'sce_sys/trophy2/eboot.bin.auth_info', b'a')
    put(root, 'sce_sys/uds/npbind.dat', npbind(['NPWR12345_00', 'NPWR54321_00']))
    put(root, 'Data/b.pak', b'b' * 300)
    put(root, 'Data/A.pak', b'a' * 200)
    put(root, 'Data/fr/voice.pak', b'f' * 64)
    put(root, 'Data/_x.bin', b'')
    put(root, 'Data/1.bin', b'1')
    put(root, 'Data/a&b.bin', b'&')
    put(root, 'Game/Saved/Config/PS5/GameUserSettings.ini', b'[x]')
    put(root, 'Game/Saved/Other/keep.bin', b'k')
    put(root, 'Game/Content/data.bin', b'd')
    put(root, 'decrypted/eboot.bin', b'copy')
    put(root, 'playgo-languages/01-en-US.bin', b'old')
    put(root, 'sce_suppl/x.bin', b'x')
    put(root, 'entitlements.txt', b'e')
    put(root, 'entitlement_key.dat', b'e')
    put(root, 'ampr_emu.index', b'i')
    put(root, 'fakelib/libSceAmpr.sprx', b'a')
    put(root, 'fakelib/libSceAppContent.sprx', b'c')
    put(root, 'old.gp5', b'<x/>')
    put(root, 'dlc_emu.ini', b'[PSAC]\r\ncontent_id=UP0000-PPSA01234_00-COMPAREDLC000001\r\nmount_point=/app0/addcont0\r\n')
    if variant == 'layout':
        chunk_dat, ht, ficm = playgo_tables(
            [('Base', ['en-US', 'fr-FR']), ('French voice', ['fr-FR']), ('', []), ('Extra', ['en-US', 'fr-FR'])],
            [('Main', 1, [0, 3]), ('Online', 2, [3, 0, 1])],
            {'eboot.bin': 0, 'Data/A.pak': 0, 'Data/b.pak': 3, 'Data/fr/voice.pak': 1, 'sce_sys/icon0.dds': 0,
             'sce_sys/keystone': 0, 'sce_sys/param.json': 0, 'Data/1.bin': 3, 'Data/not-dumped.pak': 1},
            0x1122334455667788, 0x99AABBCCDDEEFF00)
        put(root, 'sce_sys/playgo-chunk.dat', chunk_dat)
        put(root, 'sce_sys/playgo-hash-table.dat', ht)
        put(root, 'sce_sys/playgo-ficm.dat', ficm)


def reduce_project(gp5_path, dump_root, generated_roots):
    """The parts of a project that decide the package, with machine paths made comparable."""
    tree = ET.parse(gp5_path)
    root = tree.getroot()
    out = {'volume_type': root.findtext('volume/volume_type'),
           'package': {k: v for k, v in sorted(root.find('volume/package').attrib.items())}}
    ci = root.find('volume/chunk_info')
    out['chunk_info'] = dict(ci.attrib)
    chunks = ci.find('chunks')
    out['chunks_attrs'] = dict(chunks.attrib)
    out['chunks'] = [dict(c.attrib) for c in chunks.findall('chunk')]
    scenarios = ci.find('scenarios')
    out['scenarios_attrs'] = dict(scenarios.attrib)
    out['scenarios'] = [(dict(s.attrib), (s.text or '').strip()) for s in scenarios.findall('scenario')]
    files = []
    base = os.path.dirname(os.path.abspath(gp5_path))
    dump_real = os.path.realpath(dump_root)  # long names: the two tools spell the same folder differently
    for f in root.find('files').findall('file'):
        src = f.get('src_path')
        src_abs = os.path.realpath(src if os.path.isabs(src) else os.path.join(base, src))
        rel_to_dump = os.path.relpath(os.path.normcase(src_abs), os.path.normcase(dump_real))
        if not rel_to_dump.startswith('..'):
            origin = 'folder:' + os.path.relpath(src_abs, dump_real).replace(os.sep, '/')
        else:
            data = None
            candidates = [src_abs] + [os.path.join(g, f.get('dst_path').replace('/', os.sep)) for g in generated_roots]
            for c in candidates:
                if os.path.isfile(c):
                    with open(c, 'rb') as fh:
                        data = fh.read()
                    break
            origin = 'generated:' + (hashlib.sha256(data).hexdigest()[:16] + ' %d bytes' % len(data)
                                     if data is not None else 'not written at plan time')
        files.append({'dst': f.get('dst_path'), 'chunk': f.get('chunk'),
                      'pfs_compression': f.get('pfs_compression'), 'origin': origin})
    out['files'] = files
    out['empty_dirs'] = [d.get('dst_path') for d in root.find('files').findall('empty_dir')]
    return out


def load_json(path):
    with open(path, 'rb') as f:
        return json.loads(f.read().decode('utf-8-sig'))


def compare(name, ours, theirs, problems):
    if ours != theirs:
        problems.append((name, ours, theirs))


def run_variant(variant, args, work):
    dump = os.path.join(work, variant, 'dump')
    ref_out = os.path.join(work, variant, 'reference')
    our_out = os.path.join(work, variant, 'ours')
    os.makedirs(ref_out)
    os.makedirs(our_out)
    write_dump(dump, variant)

    ref_gp5 = os.path.join(ref_out, 'project.gp5')
    cmd = [sys.executable, '-I', args.script, dump, ref_gp5, '--passcode', '0' * 32, '--absolute-paths',
           '--keep-keystone', '--chunk-count', '100', '--auto-size-profile', 'sdk279']
    ref = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding='utf-8', errors='replace')
    with open(os.path.join(ref_out, 'script.log'), 'w', encoding='utf-8') as f:
        f.write(ref.stdout)
    if ref.returncode != 0:
        print(ref.stdout)
        raise SystemExit(2)

    env = dict(os.environ)
    env['FW_FPKG_COMPARE_DUMP'] = dump
    env['FW_FPKG_COMPARE_OUT'] = our_out
    env['FW_FPKG_COMPARE_MODE'] = 'script'
    if args.qt_bin:
        env['PATH'] = args.qt_bin + os.pathsep + env.get('PATH', '')
    ours = subprocess.run([args.test_exe, 'projectForComparison'], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, encoding='utf-8', errors='replace', env=env)
    if ours.returncode != 0 or not os.path.isfile(os.path.join(our_out, 'project.gp5')):
        print(ours.stdout)
        raise SystemExit(2)

    ref_assets = os.path.join(ref_out, '.gp5-assets', 'project')
    a = reduce_project(os.path.join(our_out, 'project.gp5'), dump, [os.path.join(our_out, 'generated')])
    b = reduce_project(ref_gp5, dump, [ref_assets])
    problems = []
    for key in ('volume_type', 'package', 'chunk_info', 'chunks_attrs', 'chunks', 'scenarios_attrs', 'scenarios', 'empty_dirs'):
        compare(key, a[key], b[key], problems)
    # Generated copies of executables are written when the build runs, not at plan time: compare
    # which files are replaced, not their bytes (the unit tests cover the bytes).
    def flat(files):
        rows = []
        for f in files:
            origin = f['origin']
            if origin.startswith('generated:') and f['dst'].lower().endswith(('.bin', '.prx', '.sprx', '.png')):
                origin = 'generated'
            if origin.startswith('generated:') and (f['dst'].startswith('playgo-') or f['dst'] == 'sce_sys/param.json'
                                                    or f['dst'] == 'sce_sys/playgo-scenario.json'):
                origin = 'generated'
            rows.append((f['dst'], f['chunk'], f['pfs_compression'], origin))
        return rows
    fa, fb = flat(a['files']), flat(b['files'])
    if fa != fb:
        only_ours = [r for r in fa if r not in fb]
        only_ref = [r for r in fb if r not in fa]
        if only_ours or only_ref:
            problems.append(('files', only_ours, only_ref))
        else:
            problems.append(('file order', [r[0] for r in fa], [r[0] for r in fb]))
    compare('param.json', load_json(os.path.join(our_out, 'param.json')),
            load_json(os.path.join(ref_assets, 'sce_sys', 'param.json')), problems)
    compare('playgo-scenario.json', load_json(os.path.join(our_out, 'playgo-scenario.json')),
            load_json(os.path.join(ref_out, 'project.playgo-scenario.json')), problems)
    print('[%s] %d file entries, %d chunk(s) declared: %s' % (
        variant, len(fa), len(a['chunks']), 'identical' if not problems else '%d difference(s)' % len(problems)))
    for name, ours_value, ref_value in problems:
        print('  %s' % name)
        print('    this app : %s' % json.dumps(ours_value)[:3000])
        print('    reference: %s' % json.dumps(ref_value)[:3000])
    return not problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--script', required=True, help='create-gp5-from-folder.py of the reference toolkit')
    parser.add_argument('--test-exe', required=True, help='tst_fpkg_rules.exe of this build')
    parser.add_argument('--qt-bin', help='Qt bin folder, when the test program needs it on PATH')
    parser.add_argument('--keep', help='work folder to keep (default: a temporary folder, removed afterwards)')
    parser.add_argument('--variants', default='generated,layout')
    args = parser.parse_args()
    args.script = os.path.abspath(args.script)
    args.test_exe = os.path.abspath(args.test_exe)
    for path in (args.script, args.test_exe):
        if not os.path.isfile(path):
            print('not found: %s' % path)
            return 2
    work = args.keep or tempfile.mkdtemp(prefix='fpkg-compare-')
    if args.keep:
        shutil.rmtree(work, ignore_errors=True)
    os.makedirs(work, exist_ok=True)
    try:
        ok = True
        for variant in args.variants.split(','):
            ok = run_variant(variant.strip(), args, work) and ok
        return 0 if ok else 1
    finally:
        if not args.keep:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == '__main__':
    sys.exit(main())

"""Generate the Windows version resource consumed by PyInstaller.

The version is read from ``APP_VERSION`` / ``APP_EDITION`` in
exfat_builder.py so the executable's file properties, the in-app version and
the release notes can never drift apart.

Usage:  python tools/make_version_info.py <output-file>
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_constant(name, default=None):
    path = os.path.join(ROOT, 'exfat_builder.py')
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            m = re.match(r"^%s\s*=\s*['\"]([^'\"]*)['\"]" % re.escape(name), line)
            if m:
                return m.group(1)
    if default is None:
        raise SystemExit('%s not found in exfat_builder.py' % name)
    return default


def version_tuple(version):
    parts = [int(p) for p in re.findall(r'\d+', version)[:4]]
    while len(parts) < 4:
        parts.append(0)
    return tuple(parts)


TEMPLATE = """# UTF-8
# Generated by tools/make_version_info.py - do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'kerrdec97'),
        StringStruct('FileDescription', 'exFAT Image Builder - PS5 game image toolkit'),
        StringStruct('FileVersion', '{version}'),
        StringStruct('InternalName', 'exFAT Image Builder'),
        StringStruct('LegalCopyright', 'kerrdec97 and contributors. See THIRD_PARTY_NOTICES.md.'),
        StringStruct('OriginalFilename', 'exFAT Image Builder.exe'),
        StringStruct('ProductName', 'exFAT Image Builder {edition}'),
        StringStruct('ProductVersion', '{version}'),
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    version = read_constant('APP_VERSION')
    edition = read_constant('APP_EDITION', '').strip()
    text = TEMPLATE.format(vt=version_tuple(version), version=version,
                           edition=edition).replace(
        "'exFAT Image Builder ')", "'exFAT Image Builder')")
    os.makedirs(os.path.dirname(os.path.abspath(argv[1])), exist_ok=True)
    with open(argv[1], 'w', encoding='utf-8') as f:
        f.write(text)
    print('Version resource: %s %s -> %s' % (version, edition, argv[1]))


if __name__ == '__main__':
    main(sys.argv)
